# ----------------------------------------------------------------------
# CLAUDE_MEMO.txt のパース
# ----------------------------------------------------------------------

CHAPTER_RE = re.compile(r"^第(\d+)章(?:[\s　]+(.*))?$")
SECTION_RE = re.compile(r"^(\d+)\.(\d+)[\s　]+(.+)$")
SEP_RE = re.compile(r"^-{10,}$")


def parse_memo(text: str):
    """CLAUDE_MEMO.txt を { 'X.Y': body } と { chapter_num: whole_body } に分解する。"""
    sections = {}
    chapter_only = {}
    current_id = None
    current_chapter = None
    buf = []
    started = False

    def flush():
        nonlocal buf
        body = "\n".join(buf).strip()
        if current_id is not None:
            if body:
                sections[current_id] = body
        elif current_chapter is not None:
            if body:
                chapter_only[current_chapter] = body
        buf = []

    for raw_line in text.split("\n"):
        line = raw_line.rstrip("\n")
        s = line.strip()
        if not started:
            if SEP_RE.match(s):
                started = True
            continue
        if SEP_RE.match(s):
            flush()
            current_id = None
            current_chapter = None
            continue
        m_ch = CHAPTER_RE.match(s)
        if m_ch:
            flush()
            current_chapter = m_ch.group(1)
            current_id = None
            continue
        m_sec = SECTION_RE.match(s)
        if m_sec:
            flush()
            current_id = f"{m_sec.group(1)}.{m_sec.group(2)}"
            continue
        buf.append(line)
    flush()
    return sections, chapter_only


def build_markdown(sections, chapter_only) -> str:
    lines = []
    lines.append('---')
    lines.append('title: "卒業論文 雛形（自動生成・下書き）"')
    lines.append('author: "（氏名）"')
    lines.append('date: "自動生成"')
    lines.append('---')
    lines.append("")
    lines.append("> **この雛形について（自動生成ファイル・直接編集しないこと）**")
    lines.append("> 章立ては `進捗反映版メモ.txt` 13節「卒業論文の章題構成例」、")
    lines.append("> 本文は `CLAUDE_MEMO.txt` から `build_thesis_docx.py` が自動生成した。")
    lines.append("> 内容を追記・修正する場合は `CLAUDE_MEMO.txt` を編集すること")
    lines.append("> （編集すると自動でこのファイルと.docxが再生成される）。")
    lines.append("> 未執筆の節は「・ここには〜を書く」という執筆指示のプレースホルダのまま。")
    lines.append("")
    lines.append("---")
    lines.append("")

    for chap_id, chap_title, secs in CHAPTERS:
        lines.append(f"# 第{chap_id}章　{chap_title}")
        lines.append("")

        # その章のどのsection番号もCLAUDE_MEMO.txtに登場せず、
        # かつ章見出し直下にまとまった本文がある場合(現状は第9章のみ)は
        # 節に分割せず、章全体をそのまま差し込む。
        any_section_hit = any(sid in sections for sid, _, _ in secs)
        if not any_section_hit and chap_id in chapter_only:
            lines.append(
                f"## {secs[0][0]}〜{secs[-1][0]} {chap_title}(CLAUDE_MEMO.txtより自動挿入・未分割)"
            )
            lines.append("")
            lines.append(chapter_only[chap_id])
            lines.append("")
            lines.append("---")
            lines.append("")
            continue

        for sec_id, sec_title, placeholder in secs:
            lines.append(f"## {sec_id} {sec_title}")
            lines.append("")
            if sec_id in sections:
                lines.append(sections[sec_id])
            else:
                lines.append(placeholder)
            lines.append("")
        lines.append("---")
        lines.append("")

    lines.append("# 参考文献")
    lines.append("")
    lines.append(REFERENCES_PLACEHOLDER)
    lines.append("")

    return "\n".join(lines)


def main():
    if not MEMO_PATH.exists():
        print(f"エラー: {MEMO_PATH} が見つかりません", file=sys.stderr)
        sys.exit(1)

    memo_text = MEMO_PATH.read_text(encoding="utf-8")
    sections, chapter_only = parse_memo(memo_text)

    md = build_markdown(sections, chapter_only)
    OUT_MD.write_text(md, encoding="utf-8")

    try:
        subprocess.run(
            ["pandoc", str(OUT_MD), "-o", str(OUT_DOCX), "--toc", "--toc-depth=2", "-V", "lang=ja"],
            check=True,
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:
        print("警告: pandocが見つからないため.docxは生成していません(.mdのみ更新)", file=sys.stderr)
        return
    except subprocess.CalledProcessError as e:
        print(f"pandoc変換に失敗しました:\n{e.stderr}", file=sys.stderr)
        sys.exit(1)

    print(f"更新しました: {OUT_MD.name}, {OUT_DOCX.name}")
    print(f"(埋まっている節: {len(sections)}件, 章全体挿入: {len(chapter_only)}件)")


if __name__ == "__main__":
    main()
